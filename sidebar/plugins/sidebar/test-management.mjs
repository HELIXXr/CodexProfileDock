import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {createBackend} from "./backend.mjs";
const dir=fs.mkdtempSync(path.join(os.tmpdir(),"dock-management-"));
try{
 const vault=path.join(dir,"CodexProfileDock"),home=path.join(dir,"codex"),state=path.join(dir,"state");
 fs.mkdirSync(vault);fs.mkdirSync(home);
 const exe=path.join(process.env.SystemRoot,"System32","WindowsPowerShell","v1.0","powershell.exe");
 const script=fileURLToPath(new URL("./scripts/Switch-Codex.ps1",import.meta.url));
 const security=fileURLToPath(new URL("./scripts/Vault-Security.ps1",import.meta.url));
 const init=path.join(dir,"fixture.ps1");
 fs.writeFileSync(init,"\n$ErrorActionPreference='Stop'\nAdd-Type -AssemblyName System.Security\n$scope=[Security.Cryptography.DataProtectionScope]::CurrentUser\nfunction Read-Blob($p){return ,([IO.File]::ReadAllBytes($p))}\nfunction Write-Atomic($p,[byte[]]$b){[IO.File]::WriteAllBytes($p,$b)}\nfunction Get-Identity($b){'fixture'}\n. $args[0]\nforeach($name in @('Personal','Work')){\n $claims=@{iss='fixture';sub=$name}|ConvertTo-Json -Compress\n $payload=[Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($claims)).TrimEnd('=').Replace('+','-').Replace('/','_')\n $expiry=if($name -eq 'Work'){1}else{4102444800}\n $expClaims=@{exp=$expiry}|ConvertTo-Json -Compress\n $access=[Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($expClaims)).TrimEnd('=').Replace('+','-').Replace('/','_')\n $auth=@{auth_mode='chatgpt';tokens=@{id_token=\"fixture.$payload.fixture\";access_token=\"fixture.$access.fixture\";refresh_token='fixture-refresh';account_id=$name}}|ConvertTo-Json -Compress\n $bytes=[Text.Encoding]::UTF8.GetBytes($auth)\n Save-DockProfile (Join-Path $args[1] ($name+'.dpapi')) $bytes\n if($name -eq 'Personal'){[IO.File]::WriteAllBytes((Join-Path $args[2] 'auth.json'),$bytes)}\n}\n");
 execFileSync(exe,["-NoProfile","-ExecutionPolicy","RemoteSigned","-File",init,security,vault,home],{windowsHide:true});
 const active=fs.readFileSync(path.join(home,"auth.json"));
 const b=createBackend({local:dir,userProfile:dir,codexHome:home,stateDir:state,launch:()=>assert.fail("Deleting must not launch a restart worker")});
 const info=await b.accountInfo();
 assert.deepEqual(info.current,["Personal"]);assert.equal(info.activeState,"saved");
 assert.equal(info.loginStates.Work,"expired");assert.equal(JSON.stringify(info).includes("fixture"),false);
 b.moveProfile({name:"Work",direction:-1});assert.deepEqual(b.list().profiles,["Work","Personal"]);
 const completed={id:"fixture-completed",kind:"Switch",name:"Personal",status:"requested"};
 fs.writeFileSync(path.join(state,"latest.json"),JSON.stringify(completed));
 b.confirmActiveAccount(completed);
 assert.equal(b.list().operation.status,"verified");assert.equal(b.list().busy,false);
 b.confirmActiveAccount({id:"other-operation"});
 assert.equal(b.list().operation.id,completed.id);
 const confirmation=b.prepare({action:"Delete",name:"Personal"});
 assert.equal((await b.start(confirmation)).status,"deleted");
 assert.deepEqual(fs.readFileSync(path.join(home,"auth.json")),active);
 assert.deepEqual(b.list().profiles,["Work"]);assert.equal(b.list().busy,false);
 assert.equal((await b.accountInfo()).activeState,"unsaved");
 await assert.rejects(b.start(confirmation),{message:"ticket_expired"});
 const stale=b.prepare({action:"Delete",name:"Work"});
 fs.writeFileSync(path.join(vault,"Work.dpapi"),"changed fixture");
 await assert.rejects(b.start(stale),{message:"profile_changed"});
 assert.deepEqual(fs.readFileSync(path.join(home,"auth.json")),active);
 console.log("PASS current account identification, token-age hint, confirmed deletion, replay/stale guard and unchanged active sign-in");
}finally{fs.rmSync(dir,{recursive:true,force:true});}
